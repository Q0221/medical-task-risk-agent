# ---------------------------------------------------------------------------
# 关键词粗筛
# ---------------------------------------------------------------------------

def retrieve_by_keywords(query: str, top_k: int = 3) -> list[tuple[SopDoc, float]]:
    """对内置 SOP 按关键词命中数打粗分，返回 top_k 条及分数（0~1）。"""
    query_lower = query.lower()
    scored: list[tuple[SopDoc, float]] = []
    for doc in BUILTIN_SOPS:
        hits = sum(1 for kw in doc.keywords if kw.lower() in query_lower)
        if hits > 0:
            score = min(hits / len(doc.keywords), 1.0)
            scored.append((doc, round(score, 3)))

    scored.sort(key=lambda x: x[1], reverse=True)
    return scored[:top_k]
